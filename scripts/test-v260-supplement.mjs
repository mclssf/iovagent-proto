import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';
const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const { usePhase1 } = await server.ssrLoadModule('/src/pinia/phase1.ts');
  const { useLingdongSync, readLingdongSample } = await server.ssrLoadModule('/src/pinia/lingdongSync.ts');
  const { monitoringOrder } = await server.ssrLoadModule('/src/views/Phase1/presentation.ts');
  const { getRiskOrders } = await server.ssrLoadModule('/src/views/AgentWork/utils/index.ts');
  const { projectOrderConversation: chat } = await server.ssrLoadModule('/src/views/Phase1/orderConversation.ts');
  setActivePinia(createPinia()); const m = usePhase1(), sync = useLingdongSync();
  const projects = [{ id: 'A' }, { id: 'B' }];
  assert.equal(sync.setDefault('MISSING', projects).length > 0, true);
  assert.equal(sync.setDefault('A', projects), '');
  const source = readLingdongSample(0, m.now);
  assert(sync.ingest(source, projects)); assert.equal(m.orders.length, 3);
  const blocked = m.orders.find(o => o.id === 'LD260003');
  assert.equal(blocked.billingExempt, true); assert.equal(blocked.network.status, 'unregistered');
  assert.equal(blocked.session, 'stopped'); assert.equal(m.events.length, 0);
  const projected = monitoringOrder(blocked, ['晚到']);
  assert.equal(projected.risk, '待核实'); assert.deepEqual(projected.riskTags, ['车辆未入网']);
  assert.equal(getRiskOrders([projected, monitoringOrder(blocked, [])]).length, 1, 'abnormal order count is deduplicated by order');
  assert(sync.ingest(source, projects)); assert.equal(m.orders.length, 3); assert.equal(Object.keys(sync.records).length, 3);
  assert.equal(sync.setDefault('B', projects), '');
  const newer = source.map(row => ({ ...row, updatedAt: row.updatedAt + 1, network: 'registered' }));
  assert(sync.ingest(newer, projects)); assert.equal(blocked.network.status, 'unregistered'); assert.equal(blocked.session, 'stopped'); assert(blocked.billingExempt);
  assert(m.orders.every(o => o.projectId === 'A'), 'switching default never moves existing source orders');
  const c = m.config('A'); c.deviation.routeStrategy = '距离最短'; assert(m.saveConfig('A', c, c.version));
  assert.equal(m.orders[0].routePlan.strategy, '更多人选择'); assert.equal(m.orders[0].config.deviation.routeStrategy, '更多人选择');
  const c2 = m.config('B'); c2.deviation.routeStrategy = '时间优先'; assert(m.saveConfig('B', c2, c2.version));
  assert(sync.ingest(readLingdongSample(1, m.now), projects));
  const newOrder = m.orders.find(o => o.id === 'LD260004'); assert.equal(newOrder.projectId, 'B'); assert.equal(newOrder.routePlan.strategy, '时间优先');
  assert(!sync.ingest(readLingdongSample(2, m.now), [])); assert.equal(m.orders.length, 4);
  const own = () => m.orders.filter(o => o.projectId === 'A').map(o => monitoringOrder(o, []));
  const query = chat('哪些车未入网', 'A', own(), []); assert.match(query.text, /LD260003/); assert(!query.text.includes('LD260004'));
  assert.match(chat('查询 LD260004', 'A', own(), []).text, /未找到/);
  assert.match(chat('查询 LD260001 是否已完成', 'A', own(), []).text, /待发车/);
  const pending = chat('把 LD260001 改为装货中', 'A', own(), []); assert.equal(pending.orderAction.status, 'pending'); assert.equal(m.orders[0].state, 'pending');
  const result = chat(`确认更新 ${pending.orderAction.id}`, 'A', own(), [pending]); assert.match(result.text, /已从待发车更新为装货中/); assert.equal(m.events.length, 0);
  assert.match(chat(`确认更新 ${pending.orderAction.id}`, 'A', own(), [pending]).text, /失效/);
  const cancel = chat('把 LD260001 改为在途', 'A', own(), []); chat(`取消更新 ${cancel.orderAction.id}`, 'A', own(), [cancel]); assert.equal(m.orders[0].state, 'loading');
  const conflict = chat('把 LD260001 改为在途', 'A', own(), []); m.orders[0].enteredAt -= 1;
  assert.match(chat(`确认更新 ${conflict.orderAction.id}`, 'A', own(), [conflict]).text, /未保存/);
  const before = m.orders[0].expiresAt; const complete = chat('把 LD260001 改为已完成', 'A', own(), []);
  chat(`确认更新 ${complete.orderAction.id}`, 'A', own(), [complete]); assert.equal(m.orders[0].state, 'completed'); assert.equal(m.orders[0].session, 'stopped'); assert.equal(m.orders[0].expiresAt, before);
  assert.equal(m.events.length, 0); assert.equal(Object.values(sync.records).find(r => r.orderId === 'LD260001').snapshot.orderId, 'LD260001');
  const { ensureMapSamples } = await server.ssrLoadModule('/src/views/Phase1/mapSamples.ts');
  ensureMapSamples([{ id: 'P001' }]);
  const sample = m.orders.find(o => o.id === 'V260-NET001');
  assert.equal(sample.network.status, 'unregistered'); assert(sample.billingExempt); assert.equal(sample.session, 'stopped'); assert(!sample.actualTrack?.length);
  const tracked = m.orders.find(o => o.id === 'V260-TRACK001');
  assert.equal(tracked.actualTrack.length, 7); assert(tracked.actualTrack.every(point => point.at <= m.now));
  assert.notEqual(tracked.actualTrack.at(-1).lon, tracked.destination.lon);
  const total = m.orders.length; ensureMapSamples([{ id: 'P001' }]); assert.equal(m.orders.length, total);
  console.log('PASS: inbound deduplication, default ownership, no recovery, fee exemption, new-order-only routes and project dialogue state changes');
} finally { await server.close(); }
