import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';
import { nextTick } from 'vue';
import { ElMessage } from 'element-plus';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
const memory = new Map();
const originalStorage = globalThis.localStorage;
const originalSuccess = ElMessage.success;
ElMessage.success = () => ({ close() {} });
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) };
try {
  const { agentWorkData } = await server.ssrLoadModule('/src/pinia/agentWork.ts');
  const { useAgentOpsStore } = await server.ssrLoadModule('/src/pinia/agentOps.ts');
  setActivePinia(createPinia());
  const work = agentWorkData();
  const ops = useAgentOpsStore();
  for (let number = 1; number <= 7; number++) assert(work.projects.some(project => project.id === `P00${number}`));
  assert.equal(work.projects.find(project => project.id === 'P001').name, '华东干线在途监控');
  assert.equal(work.projects.find(project => project.id === 'P001').total, 128);
  assert(work.cargoSources.length && work.cargoQuotes.length && work.privateCapacity.length);
  assert.deepEqual(work.currentProjectOrders, work.ordersSeed);
  const originalOrders = JSON.stringify(work.ordersSeed);
  const originalDates = [work.ordersStartDate, work.ordersEndDate];
  const originalMessages = JSON.stringify(work.agentMessages);
  work.switchProject(work.projects.find(project => project.id === 'PSC-PREDICTION'));
  work.syncPredictionOrders({ role: 'agent', text: '', predictionRows: [{ row: '2', order: 'NEW-001', plate: '粤A12345', startLocation: '装货地点', endLocation: '卸货地点', sourceStartTime: '2026-10-12 08:00:00' }] });
  assert.equal(work.currentProjectOrders.length, 1);
  assert.equal(JSON.stringify(work.ordersSeed), originalOrders, 'new prediction orders never replace main orders');
  work.switchProject(work.projects.find(project => project.id === 'PSC2'));
  assert.equal(work.currentProjectOrders.length, 2);
  assert.equal(work.projects.find(project => project.id === 'PSC2').total, 2);
  work.switchProject(work.projects.find(project => project.id === 'P001'));
  assert.deepEqual([work.ordersStartDate, work.ordersEndDate], originalDates, 'scenario filters do not leak into existing projects');
  assert.equal(JSON.stringify(work.agentMessages), originalMessages, 'switching preserves existing project conversation');
  work.agentMessages.push({ role: 'agent', text: '旧问题需要补充', pendingPredictionPrompt: '旧参数' });
  const retainedCount = work.agentMessages.length;
  assert.equal(work.splitProjectConversation(), true);
  assert.equal(work.agentMessages.length, retainedCount + 1);
  assert.deepEqual(work.activeChatContext, []);
  assert.equal(work.splitProjectConversation(), false);
  work.agentMessages.push({ role: 'agent', text: '', streaming: true });
  assert.equal(work.splitProjectConversation(), false, 'streaming output cannot be split');
  work.agentMessages.pop();
  work.persistActiveConversationMessages();
  assert(memory.has('iovagent_project_chats_v1'));
  const tool = ops.tools.find(tool => tool.kind === 'code' && tool.outputs.length);
  const description = tool.description;
  ops.saveCodeTool(tool.id, `${description} 更新说明`, tool.outputs);
  assert.equal(ops.toolVersions(tool.id).length, 2);
  ops.restoreCodeTool(tool.id, 1);
  assert.equal(ops.tools.find(item => item.id === tool.id).description, description);
  assert.equal(ops.toolVersions(tool.id).length, 3);
  const skill = ops.skills.find(skill => skill.id === 'route-risk-expert');
  const originalName = skill.name;
  skill.name = '更新的在途风险专家';
  await nextTick();
  assert.equal(ops.getSkillVersions(skill.id).length, 2);
  ops.restoreSkillVersion(skill.id, 1);
  await nextTick();
  assert.equal(ops.skills.find(item => item.id === skill.id).name, originalName);
  assert.equal(ops.getSkillVersions(skill.id).length, 3);
  console.log('PASS: additive projects, data/filter isolation, preserved main catalogs, manual conversation boundaries, Tool and Skill history/restore.');
} finally {
  globalThis.localStorage = originalStorage;
  ElMessage.success = originalSuccess;
  await server.close();
}
