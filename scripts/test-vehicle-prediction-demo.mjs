import assert from 'node:assert/strict';
import { demoRows, evaluateDemoRow, parseTextInput, extractAdministrativeRegion, createWaybillVerificationFixtures } from '../src/views/AgentWork/vehiclePredictionDemo.ts';

const evaluate = (input) => evaluateDemoRow({ file: 'test.xlsx', sheet: '输入', row: 2, input }, 0);
const waybill = { '订单号': 'ORDER-1', '车牌号': '晋DW6759', '发货工厂': '源发货工厂', '收货地址': '山西省晋中市和顺县收货地点', '进厂时间': '2026-08-01 10:32:30', '出厂时间': '2026-08-01 11:00:47', '订单结束时间': '2026-08-01 12:55:05' };
const verificationRows = Array.from({ length: 6 }, (_, index) => createWaybillVerificationFixtures(waybill, index));
assert.deepEqual(verificationRows.map((row) => row[8]), ['通过', '不通过', '通过', '通过', '无法判断', '通过']);
for (const row of verificationRows) {
  assert.equal(row.length, 9);
  assert.ok(row.every((cell) => cell.trim()));
  assert.match(row[5], /2026-08-01 11:00:47/);
  assert.match(row[7], /2026-08-01 12:55:05/);
  assert.match(row[1], /源发货工厂/);
  assert.match(row[3], /山西省晋中市和顺县收货地点/);
  assert.doesNotMatch(row.join(' '), /返回1006|当前定位/);
}
assert.equal(createWaybillVerificationFixtures({ ...waybill, '出厂时间': '2026-02-30 08:00:00' }, 0)[0], '无法判断');
assert.equal(createWaybillVerificationFixtures({ ...waybill, '订单结束时间': '2026-08-01 09:00:00' }, 0)[8], '无法判断');
assert.equal(createWaybillVerificationFixtures({ ...waybill, '收货地址': '未知' }, 0)[2], '无法判断');
assert.deepEqual(createWaybillVerificationFixtures(waybill, 0), verificationRows[0]);
const valid = demoRows[0];
assert.equal(evaluate(valid).status, '成功');
assert.equal(evaluate({ ...valid, startAddress: '佛山市南海区某路1号', startTags: '', startMatchThreshold: '' }).start, '已有地址，未预测');
const both = evaluate({ startAddress: '装货路1号', endAddress: '卸货路2号' });
assert.equal(both.status, '已跳过');
assert.equal(both.traceId, '');
assert.equal(both.startCoord, '');
assert.equal(evaluate({ ...valid, startAddress: '未知', startTags: '' }).status, '待补充');
assert.equal(evaluate({ ...valid, startTags: '重点客户、月结' }).status, '待补充');
assert.equal(evaluate({ ...valid, startTags: '', startPoiText: '某某物流有限公司' }).status, '待补充');
assert.equal(evaluate({ ...valid, genericTags: '仓库' }).status, '待补充');
assert.equal(evaluate({ ...valid, startTags: '废品场、仓库' }).status, '地点歧义');
assert.equal(evaluate({ ...valid, startPoiText: '广州仓库' }).status, '地点歧义');
assert.equal(evaluate({ ...valid, startTime: '2026-02-30 08:00:00' }).status, '参数错误');
assert.equal(evaluate({ ...valid, endTime: valid.startTime }).status, '参数错误');
assert.equal(evaluate({ ...valid, startMatchThreshold: '1.2' }).status, '参数错误');
assert.equal(evaluate({ ...valid, stopDurationThreshold: '0' }).status, '参数错误');
assert.equal(evaluate({ ...valid, plateNo: '', vid: 'vehicle-1' }).source.input.vid, 'vehicle-1');
const original = structuredClone(valid);
evaluate(valid);
assert.deepEqual(valid, original);
assert.deepEqual(parseTextInput('预测真实装货地\n车牌号: 粤A12347\n开始时间: 2026-10-12 08:00:00\n起点匹配阈值: 0.8').plateNo, '粤A12347');
assert.equal(evaluate(demoRows[1]).status, '成功');
assert.equal(evaluate(demoRows[2]).status, '成功');
assert.match(evaluate(valid).startPoi, /佛山市南海区.*再生资源.*装货月台/);
assert.match(evaluate(valid).endPoi, /广州市白云区.*仓储.*卸货月台/);
assert.ok(evaluate(valid).startStop > valid.startTime);
assert.ok(evaluate(valid).endStop < valid.endTime);
assert.ok(evaluate(valid).startStop < evaluate(valid).endStop);
assert.deepEqual(evaluate(valid), evaluate(valid), 'Every execution generates the same valid fixture');
for (const row of [...demoRows, {}]) {
  const result = evaluate(row);
  assert.ok(result.startDisplay.trim());
  assert.ok(result.endDisplay.trim());
}
const blocked = evaluate({ ...valid, startTags: '' });
assert.equal(blocked.status, '待补充');
assert.doesNotMatch(blocked.startDisplay, /兜底模拟样例，非预测结果/);
assert.equal(blocked.startPoi, '');
assert.equal(evaluate({ ...valid, startAddress: '原装货地址1号' }).startDisplay, '原装货地址1号');
assert.equal(extractAdministrativeRegion('广东省佛山市顺德区某路88号'), '广东省佛山市顺德区');
assert.equal(extractAdministrativeRegion('上海市浦东新区某路8号'), '上海市浦东新区');
assert.equal(extractAdministrativeRegion('江苏省苏州市昆山市某路8号'), '江苏省苏州市昆山市');
const regional = evaluate({ ...valid, startOrgAddress: '广东省佛山市顺德区某大道18号' });
assert.match(regional.startDisplay, /^广东省佛山市顺德区/);
assert.doesNotMatch(regional.startDisplay, /南海区/);
const regionalBlocked = evaluate({ ...valid, startTags: '', startOrgAddress: '浙江省杭州市余杭区某路8号' });
assert.match(regionalBlocked.startDisplay, /^浙江省杭州市余杭区/);
assert.equal(regionalBlocked.status, '待补充');
const beforeRegionChange = evaluate(valid);
const afterRegionChange = evaluate({ ...valid, startOrgAddress: '上海市浦东新区示例路18号' });
assert.match(afterRegionChange.startPoi, /^上海市浦东新区/);
assert.match(afterRegionChange.startDisplay, /^上海市浦东新区/);
assert.equal(afterRegionChange.endPoi, beforeRegionChange.endPoi, 'Loading region must not alter unloading POI');
assert.equal(afterRegionChange.endDisplay, beforeRegionChange.endDisplay, 'Loading region must not alter unloading display');
assert.equal(afterRegionChange.endCoord, beforeRegionChange.endCoord, 'Loading region must not alter unloading coordinates');
console.log('Vehicle prediction demo: validation, independent skips, ambiguity and source preservation passed.');
