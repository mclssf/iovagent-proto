import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';
import { startMcpFixture } from './helpers/mcpFixture.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const vite = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
const fixture = await startMcpFixture();
try {
  const { inspectMcpServer } = await vite.ssrLoadModule('/src/views/AgentOps/mcpConnection.ts');
  const { useAgentOpsStore } = await vite.ssrLoadModule('/src/pinia/agentOps.ts');
  const { agentConfigurationFingerprint, analyzeAgentConflicts } = await vite.ssrLoadModule('/src/views/AgentOps/agentConflicts.ts');
  setActivePinia(createPinia());
  const store = useAgentOpsStore();
  const config = { name: '同步验证', description: '', transport: 'Streamable HTTP', endpoint: `${fixture.url}/mcp`, auth: 'Bearer Token', bearerToken: 'fixture-only-token', headers: [{ key: 'X-Region', value: 'east' }], timeout: 2 };
  const inspect = (overrides = {}) => inspectMcpServer({ ...config, ...overrides }, { listTools: true, signal: new AbortController().signal, onConnected: () => {} });
  for (const [path, transport] of [['/mcp', 'Streamable HTTP'], ['/streaming', 'Streamable HTTP'], ['/sse', 'SSE Legacy Transport']]) {
    fixture.state.requests.length = 0;
    const result = await inspect({ endpoint: fixture.url + path, transport });
    assert.equal(result.protocolVersion, '2025-06-18');
    assert.equal(result.serverVersion, '1.2.3');
    assert.deepEqual(result.methods.map(tool => tool.name), ['get_weather', 'check_address']);
    assert.equal(result.methods[0].outputSchema.properties.temperature.type, 'number');
    assert.equal(fixture.state.requests.filter(request => request.method === 'tools/list').length, 2, 'all pages requested');
    assert(fixture.state.requests.every(request => request.headers.authorization === 'Bearer fixture-only-token'));
    assert(!fixture.state.requests.some(request => request.method === 'tools/call'));
    if (transport === 'Streamable HTTP') assert(fixture.state.requests.filter(request => request.method === 'tools/list').every(request => request.headers['mcp-session-id'] === 'fixture-session' && request.headers['mcp-protocol-version'] === '2025-06-18'));
  }
  await assert.rejects(inspect({ endpoint: `${fixture.url}/unauthorized` }), /认证失败/);
  await assert.rejects(inspect({ endpoint: `${fixture.url}/cross-origin`, transport: 'SSE Legacy Transport' }), /同源/);
  fixture.state.duplicate = true;
  await assert.rejects(inspect(), /重复/);
  fixture.state.duplicate = false;
  fixture.state.malformed = true;
  await assert.rejects(inspect(), /Schema/);
  fixture.state.malformed = false;
  fixture.state.protocol = '2099-01-01';
  await assert.rejects(inspect(), /协议版本/);
  fixture.state.protocol = '2025-06-18';
  fixture.state.delay = 1100;
  await assert.rejects(inspect({ timeout: 1 }), /超时/);
  fixture.state.delay = 0;

  const saved = store.saveMcp(config), id = saved.id;
  const service = () => store.tools.find(tool => tool.id === id);
  const customer = 'ent-demo', agent = 'general-chat-agent';
  store.saveCustomerAgents(customer, [{ agentId: agent, mode: 'custom', skillIds: [], toolIds: [id] }]);
  store.skills[0].privateToolIds.push(id);
  const refs = JSON.stringify([store.customers, store.skills[0].privateToolIds]);
  fixture.state.requests.length = 0;
  assert(await store.testMcpConnection(id));
  assert.equal(service().connectionStatus, 'connected');
  assert.equal(service().lastSyncedAt, '');
  assert.equal(service().methods.length, 0);
  assert(!fixture.state.requests.some(request => request.method === 'tools/list'), 'connection test does not synchronize definitions');
  assert(await store.syncMcpTools(id));
  const firstSynced = service().lastSyncedAt;
  assert.equal(service().methods.length, 2);
  assert.equal(service().syncStatus, 'success');
  assert.match(service().syncResult, /新增 2/);
  const scope = () => store.resolveCustomerAgent(customer, agent);
  const catalog = () => ({ skills: store.agentCallableSkills, tools: store.tools });
  const fingerprint = agentConfigurationFingerprint(scope(), catalog());
  assert(!fingerprint.includes(config.bearerToken), 'reports never serialize authentication secrets');
  await store.testMcpConnection(id);
  assert.equal(agentConfigurationFingerprint(scope(), catalog()), fingerprint, 'status-only changes do not invalidate conflict reports');
  fixture.state.failure = true;
  assert.equal(await store.syncMcpTools(id), false);
  assert.equal(service().methods.length, 2);
  assert.equal(service().lastSyncedAt, firstSynced);
  assert.equal(service().syncStatus, 'error');
  assert(!service().syncResult.includes('server-error-must-not-be-exposed'));
  assert.equal(service().connectionStatus, 'connected', 'tools/list failure is distinct from successful initialization');
  fixture.state.failure = false;
  fixture.state.methods = [{ ...fixture.state.methods[0], description: '新版天气描述' }];
  assert(await store.syncMcpTools(id));
  assert.equal(service().methods.length, 1);
  assert.match(service().syncResult, /更新 1、移除 1/);
  assert.notEqual(agentConfigurationFingerprint(scope(), catalog()), fingerprint);
  assert.equal(analyzeAgentConflicts(scope(), catalog()).schemaCount, 1);
  assert.equal(JSON.stringify([store.customers, store.skills[0].privateToolIds]), refs, 'sync never rewrites customer or private loading assignments');
  fixture.state.empty = true;
  assert(await store.syncMcpTools(id));
  assert.equal(service().methods.length, 0);
  assert.equal(service().discovery, 'synced');
  assert(!analyzeAgentConflicts(scope(), catalog()).findings.some(finding => finding.id.startsWith('undiscovered-')));
  fixture.state.empty = false;

  let complete;
  const pending = store.syncMcpTools(id, () => new Promise(resolve => { complete = resolve; }));
  assert.equal(service().activity, 'syncing');
  assert.equal(await store.syncMcpTools(id), false, 'duplicate operations are blocked');
  store.saveMcp({ ...service(), transport: 'SSE Legacy Transport', endpoint: `${fixture.url}/sse` }, id);
  complete({ methods: fixture.state.methods, protocolVersion: '2025-06-18', provider: 'late', serverVersion: '1' });
  assert.equal(await pending, false, 'late responses cannot overwrite a changed connection');
  assert.equal(service().discovery, 'pending');
  assert.equal(service().protocolVersion, '');
  assert.equal(service().activity, 'idle');
  assert(await store.syncMcpTools(id));
  const deleting = store.syncMcpTools(id, () => new Promise(resolve => { complete = resolve; }));
  store.deleteMcp(id);
  complete({ methods: fixture.state.methods, protocolVersion: '2025-06-18', provider: 'late', serverVersion: '1' });
  assert.equal(await deleting, false);
  assert.equal(service(), undefined, 'late responses cannot resurrect deleted services');
  console.log('Passed: HTTP JSON/SSE and legacy SSE, handshake/session/auth, pagination, schemas, timeout/auth failures, atomic synchronization, empty lists, stale-result protection, references and credential-free fingerprints.');
} finally { await fixture.close(); await vite.close(); }
