import assert from 'node:assert/strict';
import {verifyWaybill} from '../server/waybill-risk.mjs';
const fmt=t=>new Date(t+8*3600000).toISOString().slice(0,19).replace('T',' ');
const now=Date.now();
const order={id:'test',plate:'测试001',customerRecord:{fields:{'发车时间':fmt(now-5*3600000),'预约提货时间':fmt(now-6*3600000),'预约送货时间':fmt(now-3600000),'到货确认时间':fmt(now-2*3600000)}}};
const input={origin:[114.1,30.1],destination:[114.2,30.2],color:'2'};
let calls=[];
const query=async(path,params)=>{calls.push([path,params]);if(path==='trackDistinguish')return {compareResults:'3',pointSize:20,jpNum:0};return {result:'0',eventTime:fmt(now-2*3600000),timeSize:0};};
const a=await verifyWaybill(order,input,query);
assert.equal(a.items.find(i=>i.name==='轨迹漂移').status,'正常');
assert.equal(a.items.find(i=>i.name==='运单真实性').status,'轨迹支持');
assert.equal(a.items.find(i=>i.name==='线路偏离').status,'待核实');
assert.ok(calls.filter(([path])=>path.includes('Backtrack')).every(([,p])=>Date.parse(p.queryTime.replace(' ','T')+'+08:00')+36*3600000<=Date.now()));
const jumped=await verifyWaybill(order,input,async(path)=>path==='trackDistinguish'?{compareResults:'1,4',pointSize:30,jpNum:2}:{result:'-1'});
assert.equal(jumped.risk,'高风险');assert.equal(jumped.items.find(i=>i.name==='运单真实性').status,'待核实');
const empty=await verifyWaybill(order,input,async(path)=>path==='trackDistinguish'?{compareResults:'5',pointSize:0,jpNum:0}:{result:'-1'});
assert.equal(empty.items.find(i=>i.name==='轨迹漂移').status,'待核实');
const failed=await verifyWaybill(order,input,async()=>{throw Error('接口失败');});assert.equal(failed.risk,'待核实');
const missing=await verifyWaybill(order,{},query);assert.equal(missing.items.find(i=>i.name==='晚到').status,'待核实');
const late=await verifyWaybill(order,input,async(path)=>path==='trackDistinguish'?{compareResults:'3',pointSize:20,jpNum:0}:{result:'1',eventTime:fmt(now-1800000),timeSize:1800});
assert.equal(late.items.find(i=>i.name==='晚到').status,'异常');
console.log('Passed: API codes, offline/empty, incomplete evidence, delays, authenticity limits, read-only route checks and future-window protection.');
