import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const { useAgentOpsStore } = await server.ssrLoadModule('/src/pinia/agentOps.ts');
  const { analyzeAgentConflicts, agentConfigurationFingerprint, resolveAgentTools } = await server.ssrLoadModule('/src/views/AgentOps/agentConflicts.ts');
  setActivePinia(createPinia());
  const store = useAgentOpsStore();
  const catalog = () => ({ skills: store.skills, tools: store.tools, globalToolIds: store.globalToolIds });
  const transit = store.agents[0];
  const operations = store.agents[1];
  assert.equal(store.globalToolIds.length, 0, 'all tools default to global loading off');
  const transitReport = store.detectAgentConflicts(transit.id);
  assert.equal(transitReport.findings.filter((finding) => finding.kind === 'duplicate').length, 2);
  assert(transitReport.findings.find((finding) => finding.id === 'duplicate-vehicle-mcp').paths.length === 4, 'all private and direct paths are included');
  assert.equal(store.detectAgentConflicts(operations.id).findings.length, 0, 'different functions are not treated as ambiguous');
  assert.equal(store.detectAgentConflicts('capacity-agent').findings.length, 0, 'sharing a dependency alone is not a conflict');
  assert(transitReport.coverage.some((note) => note.includes('未声明') && note.includes('MCP')));

  const originalSkills = JSON.stringify(store.skills);
  const originalTools = JSON.stringify(store.tools);
  const draft = { name: '边界测试 Agent', systemPrompt: '测试 Agent 的能力调用。', skillIds: ['route-risk-expert'], toolIds: ['risk-evaluate'] };
  const saved = store.saveAgent(draft);
  draft.skillIds.push('operations-sms-notification');
  assert.deepEqual(saved.skillIds, ['route-risk-expert'], 'saved arrays are detached from the editor draft');
  assert.equal(JSON.stringify(store.skills), originalSkills, 'Agent edits preserve Skill private bindings');
  assert.equal(JSON.stringify(store.tools), originalTools, 'Agent edits preserve engineering-owned definitions');
  assert.equal(store.globalToolIds.length, 0, 'direct assignments do not enable global loading');
  const directIds = [...saved.toolIds];
  store.setToolGlobalLoading('risk-evaluate', true);
  assert.deepEqual(saved.toolIds, directIds);
  assert.equal(JSON.stringify(store.skills), originalSkills);
  const globalReport = store.detectAgentConflicts(saved.id);
  assert.equal(globalReport.findings.find((finding) => finding.id === 'duplicate-risk-evaluate').paths.length, 3);
  store.setToolGlobalLoading('risk-evaluate', false);
  assert.notEqual(globalReport.fingerprint, agentConfigurationFingerprint(saved, catalog()), 'global edits invalidate old reports');
  assert.deepEqual(saved.toolIds, directIds);

  const noDirect = store.saveAgent({ ...saved, toolIds: [] }, saved.id);
  const privateReport = store.detectAgentConflicts(noDirect.id);
  assert.equal(privateReport.findings.length, 0, 'a Skill with its own private tool is an ordinary dependency');
  assert(resolveAgentTools(noDirect, catalog()).some((usage) => usage.id === 'risk-evaluate'));
  const skill = store.skills.find((item) => item.id === 'route-risk-expert');
  skill.privateToolIds = skill.privateToolIds.filter((id) => id !== 'risk-evaluate');
  assert.notEqual(privateReport.fingerprint, agentConfigurationFingerprint(noDirect, catalog()), 'Skill private binding edits invalidate old reports');
  assert.deepEqual(noDirect.toolIds, [], 'Skill edits do not rewrite Agent direct assignments');
  store.saveAgent({ ...noDirect, toolIds: ['risk-evaluate'] }, noDirect.id);
  const latestAgent = store.agents.find((item) => item.id === noDirect.id);
  const ambiguity = store.detectAgentConflicts(latestAgent.id);
  assert(ambiguity.findings.some((finding) => finding.kind === 'intent' && finding.evidence.some((evidence) => evidence.includes('评估在途风险'))), 'different identities with overlapping intent yield explainable ambiguity');
  skill.enabled = false;
  const disabled = store.detectAgentConflicts(latestAgent.id);
  assert(disabled.findings.some((finding) => finding.id === 'disabled-skill-route-risk-expert'));
  assert(!resolveAgentTools(latestAgent, catalog()).some((usage) => usage.id === 'vehicle-mcp'), 'disabled Skill dependencies are excluded');
  assert(resolveAgentTools(latestAgent, catalog()).some((usage) => usage.id === 'risk-evaluate'), 'disabled Skill does not disable an independently loaded tool');
  const beforePromptEdit = agentConfigurationFingerprint(latestAgent, catalog());
  latestAgent.systemPrompt += '\n新路由约定';
  assert.notEqual(beforePromptEdit, agentConfigurationFingerprint(latestAgent, catalog()));

  const parameter = (name, type) => ({ name, type, required: true, description: name });
  const code = (id, description, inputs, outputs) => ({ id, name: id, description, kind: 'code', inputs, outputs, runtime: 'Python 3', entrypoint: 'tools/test.py:run', updatedAt: '' });
  const sharedSchema = [parameter('payload', 'object'), parameter('options', 'object')];
  const sharedOutput = [parameter('result', 'object')];
  const tools = [code('archive', '归档业务附件', sharedSchema, sharedOutput), code('calculate', '计算账期费用', sharedSchema, sharedOutput)];
  const schemaReport = analyzeAgentConflicts({ name: 'Schema测试', systemPrompt: '处理任务', skillIds: [], toolIds: tools.map((tool) => tool.id) }, { skills: [], tools, globalToolIds: [] });
  assert.equal(schemaReport.findings[0].kind, 'schema');
  assert.equal(schemaReport.findings[0].severity, 'review', 'identical Schema only warrants review, not a confirmed functional conflict');
  tools[1].inputs = [parameter('amount', 'number')];
  assert.equal(analyzeAgentConflicts({ name: '测试', systemPrompt: '测试', skillIds: [], toolIds: ['archive', 'calculate'] }, { skills: [], tools, globalToolIds: [] }).findings.length, 0);
  const missing = analyzeAgentConflicts({ name: '失效测试', systemPrompt: '测试', skillIds: ['missing-skill'], toolIds: ['missing-tool'] }, { skills: [], tools: [], globalToolIds: [] });
  assert.equal(missing.findings.length, 2);
  assert.equal(missing.toolCount, 0);
  const noScope = analyzeAgentConflicts({ name: '空测试', systemPrompt: '', skillIds: [], toolIds: [] }, { skills: [], tools: [], globalToolIds: [] });
  assert(noScope.coverage.some((note) => note.includes('没有有效')));
  assert(noScope.findings.some((finding) => finding.id === 'empty-prompt'));
  assert.throws(() => store.saveAgent({ ...saved, name: '' }), /填写/);
  assert.throws(() => store.saveAgent({ ...saved, name: operations.name }), /已存在/);
  const globalsBeforeDelete = [...store.globalToolIds];
  store.deleteAgent(saved.id);
  assert(!store.agents.some((agent) => agent.id === saved.id));
  assert(!store.agentReports[saved.id]);
  assert.deepEqual(store.globalToolIds, globalsBeforeDelete);
  assert.equal(JSON.stringify(store.tools), originalTools);
  console.log('Agent conflict and configuration tests passed (paths, intents, schemas, independence, stale reports, invalid references, CRUD).');
} finally {
  await server.close();
}
