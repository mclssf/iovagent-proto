import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const { useAgentOpsStore } = await server.ssrLoadModule('/src/pinia/agentOps.ts');
  const { analyzeAgentConflicts, agentConfigurationFingerprint, resolveAgentTools } = await server.ssrLoadModule('/src/views/AgentOps/agentConflicts.ts');
  setActivePinia(createPinia());
  const store = useAgentOpsStore();
  const catalog = () => ({ skills: store.agentCallableSkills, tools: store.tools });
  assert.deepEqual(store.agents.map((agent) => agent.name), ['数据员工 Agent', '通用对话 Agent', '项目对话 Agent']);
  const dataAgent = store.agents.find((agent) => agent.role === 'data-employee');
  const generalAgent = store.agents.find((agent) => agent.role === 'general-chat');
  const projectAgent = store.agents.find((agent) => agent.role === 'project-chat');
  const { selectSkillGroup } = await server.ssrLoadModule('/src/pinia/customerAgents.ts');
  const customerId = 'ent-jinyu', otherCustomerId = 'ent-tsingtao';
  const config = (agentId, skillIds = [], toolIds = []) => ({ agentId, skillIds, toolIds });
  const scope = (id, agentId) => store.resolveCustomerAgent(id, agentId);
  const detect = (id, agentId) => store.detectCustomerAgentConflicts(id, agentId);
  assert(store.agents.every(agent => !('skillIds' in agent) && !('toolIds' in agent)), 'base Agents cannot own loading assignments');
  assert.equal(store.customers.length, 8);
  assert(store.customers.every(customer => customer.contractStart < customer.contractEnd && ['试用', '正式'].includes(customer.activationType)));
  assert(store.agentCallableSkills.every(skill => ['基础 Skill 组', '扩展 Skill 组', '定制 Skill 组'].includes(skill.group) && !('visibility' in skill) && !('enterpriseIds' in skill)));
  assert(store.availableSkillsForAgent(dataAgent.id).every(skill => skill.source === 'data-employee'));
  assert(store.availableSkillsForAgent(generalAgent.id).every(skill => skill.source === 'common'));
  assert(store.availableSkillsForAgent(projectAgent.id).every(skill => skill.source === 'common'));
  const otherBefore = JSON.stringify(store.customers.find(customer => customer.id === otherCustomerId));
  const originalSkills = JSON.stringify(store.skills), originalTools = JSON.stringify(store.tools);
  const assignment = [config(dataAgent.id, ['jinyu-cement-tms']), config(projectAgent.id, ['route-risk-expert'], ['risk-evaluate'])];
  store.saveCustomerAgents(customerId, assignment);
  assignment[0].skillIds.push('scan-login-tms');
  assert.deepEqual(scope(customerId, dataAgent.id).skillIds, ['jinyu-cement-tms'], 'saved selections detach from draft');
  assert.equal(JSON.stringify(store.customers.find(customer => customer.id === otherCustomerId)), otherBefore, 'saving one customer cannot affect another');
  assert.equal(JSON.stringify(store.skills), originalSkills, 'customer assignment preserves private definitions');
  assert.equal(JSON.stringify(store.tools), originalTools);
  assert.throws(() => scope(customerId, generalAgent.id), /尚未配置/);
  assert.throws(() => store.saveCustomerAgents('missing', []), /不存在/);
  const beforeInvalid = JSON.stringify(store.customers);
  for (const invalid of [[config('missing')], [config(dataAgent.id, ['route-risk-expert'])], [config(generalAgent.id, ['jinyu-cement-tms'])], [config(generalAgent.id, [], ['missing'])], [config(generalAgent.id), config(generalAgent.id)], [config(generalAgent.id, ['capacity-cargo-search'])]]) {
    assert.throws(() => store.saveCustomerAgents(customerId, [config(projectAgent.id), ...invalid]));
    assert.equal(JSON.stringify(store.customers), beforeInvalid, 'invalid draft applies no partial assignments');
  }
  const dataReport = detect(customerId, dataAgent.id);
  assert.equal(dataReport.skillCount, 1);
  const employee = store.dataEmployeeSkills[0];
  const allCustomerBindings = JSON.stringify(store.customers);
  store.saveDataEmployeeSkill({ ...employee, name: '金隅水泥采集 Skill', loginUrl: 'https://jinyu.example.com/login', skillContent: '# 新版采集指引', skillVersion: 'v2.0', privateToolIds: ['spreadsheet-export'] });
  const mappedSkill = store.agentCallableSkills.find(skill => skill.id === employee.id);
  assert.equal(mappedSkill.content, '# 新版采集指引');
  assert.equal(mappedSkill.sourceConfig.loginUrl, 'https://jinyu.example.com/login');
  assert.notEqual(dataReport.fingerprint, agentConfigurationFingerprint(scope(customerId, dataAgent.id), catalog()));
  assert(resolveAgentTools(scope(customerId, dataAgent.id), catalog()).some(usage => usage.id === 'spreadsheet-export'));
  assert(store.skillsForTool('spreadsheet-export').some(skill => skill.id === employee.id), 'private usage includes data employee Skills');
  const added = { ...employee, id: 'new-data-source', privateToolIds: ['datetime-format'] };
  store.saveDataEmployeeSkill(added);
  added.privateToolIds.push('vehicle-mcp');
  assert.deepEqual(store.dataEmployeeSkills.find(skill => skill.id === added.id).privateToolIds, ['datetime-format']);
  assert.equal(JSON.stringify(store.customers), allCustomerBindings, 'adding or editing a Skill never grants it to customers automatically');

  const groupCatalog = store.availableSkillsForAgent(generalAgent.id);
  const baseIds = selectSkillGroup([], '基础 Skill 组', groupCatalog, true);
  assert(baseIds.length > 1 && baseIds.every(id => groupCatalog.find(skill => skill.id === id).group === '基础 Skill 组'));
  assert.deepEqual(selectSkillGroup(baseIds, '基础 Skill 组', groupCatalog, true), baseIds, 'bulk selection is idempotent');
  assert.deepEqual(selectSkillGroup([...baseIds, 'route-risk-expert'], '基础 Skill 组', groupCatalog, false), ['route-risk-expert']);
  assert(!selectSkillGroup([], '扩展 Skill 组', groupCatalog, true).includes('capacity-cargo-search'), 'batch excludes disabled Skills');
  store.saveCustomerAgents('ent-demo', [config(generalAgent.id, baseIds)]);
  const beforeRegroup = JSON.stringify(store.customers);
  const regrouped = store.skills.find(skill => skill.id === baseIds[0]);
  regrouped.group = '定制 Skill 组';
  store.skills.push({ ...regrouped, id: 'new-base-skill', group: '基础 Skill 组' });
  assert.equal(JSON.stringify(store.customers), beforeRegroup, 'group membership changes cannot mutate saved grants');
  store.saveCustomerAgents('ent-demo', []);
  assert.equal(store.customers.find(customer => customer.id === 'ent-demo').agentConfigs.length, 0, 'all Agents can be revoked');

  const transit = { name: '在途测试', systemPrompt: '测试在途能力', skillIds: ['route-risk-expert', 'vehicle-location-query', 'vehicle-trace-query'], toolIds: ['vehicle-mcp', 'risk-evaluate'] };
  const operations = { name: '运营测试', systemPrompt: '测试运营能力', skillIds: ['operations-logistics-sheet', 'operations-sms-notification'], toolIds: ['datetime-format'] };
  const capacity = { name: '运力测试', systemPrompt: '测试运力能力', skillIds: ['capacity-find-carrier', 'capacity-quote-query', 'capacity-private-fleet'], toolIds: [] };
  assert.equal(store.globalToolIds, undefined);
  assert.equal(store.setToolGlobalLoading, undefined);
  const transitReport = analyzeAgentConflicts(transit, catalog());
  assert.equal(transitReport.findings.filter(finding => finding.kind === 'duplicate').length, 2);
  assert.equal(transitReport.findings.find(finding => finding.id === 'duplicate-vehicle-mcp').paths.length, 4);
  assert.equal(analyzeAgentConflicts(operations, catalog()).findings.length, 0);
  assert.equal(analyzeAgentConflicts(capacity, catalog()).findings.length, 0, 'sharing private dependencies alone is not a conflict');
  const directReport = detect(customerId, projectAgent.id);
  assert(directReport.findings.some(finding => finding.id === 'duplicate-risk-evaluate'));
  const otherReport = detect(otherCustomerId, projectAgent.id);
  assert(!otherReport.findings.some(finding => finding.id === 'duplicate-risk-evaluate'), 'detection uses the current customer scope only');
  assert.equal(store.customerReports[customerId][projectAgent.id].fingerprint, directReport.fingerprint);
  assert.equal(store.customerReports[otherCustomerId][projectAgent.id].fingerprint, otherReport.fingerprint);
  assert(store.customerAgentsForTool('risk-evaluate').some(usage => usage.customerId === customerId && usage.agentId === projectAgent.id && usage.name.includes('金隅水泥')));
  assert(!store.customerAgentsForTool('risk-evaluate').some(usage => usage.customerId === otherCustomerId));
  const isolated = { ...generalAgent, skillIds: [], toolIds: [] };
  assert.equal(resolveAgentTools(isolated, { ...catalog(), globalToolIds: ['risk-evaluate'] }).length, 0);
  store.saveCustomerAgents(customerId, [config(projectAgent.id, ['route-risk-expert'])]);
  const noDirect = scope(customerId, projectAgent.id);
  assert.notEqual(directReport.fingerprint, agentConfigurationFingerprint(noDirect, catalog()));
  const privateReport = detect(customerId, projectAgent.id);
  assert.equal(privateReport.findings.length, 0);
  assert(resolveAgentTools(noDirect, catalog()).some(usage => usage.id === 'risk-evaluate'));
  const skill = store.skills.find(item => item.id === 'route-risk-expert');
  skill.privateToolIds = skill.privateToolIds.filter(id => id !== 'risk-evaluate');
  assert.notEqual(privateReport.fingerprint, agentConfigurationFingerprint(noDirect, catalog()));
  store.saveCustomerAgents(customerId, [config(projectAgent.id, ['route-risk-expert'], ['risk-evaluate'])]);
  assert(detect(customerId, projectAgent.id).findings.some(finding => finding.kind === 'intent'));
  skill.enabled = false;
  assert(detect(customerId, projectAgent.id).findings.some(finding => finding.id === 'disabled-skill-route-risk-expert'));
  assert(!resolveAgentTools(scope(customerId, projectAgent.id), catalog()).some(usage => usage.id === 'vehicle-mcp'));
  assert(resolveAgentTools(scope(customerId, projectAgent.id), catalog()).some(usage => usage.id === 'risk-evaluate'));
  const customerBeforePrompt = JSON.stringify(store.customers);
  const saved = store.saveAgent({ name: '新版项目 Agent', systemPrompt: '更新共享指令', skillIds: ['ignored'], toolIds: ['ignored'] }, projectAgent.id);
  assert(!('skillIds' in saved) && !('toolIds' in saved), 'base save cannot reintroduce loading');
  assert.equal(JSON.stringify(store.customers), customerBeforePrompt);
  assert.equal(scope(otherCustomerId, projectAgent.id).systemPrompt, '更新共享指令');
  assert.notEqual(otherReport.fingerprint, agentConfigurationFingerprint(scope(otherCustomerId, projectAgent.id), catalog()));
  const parameter = (name, type) => ({ name, type, required: true, description: name });
  const code = (id, description, inputs, outputs) => ({ id, name: id, description, kind: 'code', inputs, outputs, runtime: 'Python 3', entrypoint: 'tools/test.py:run', updatedAt: '' });
  const sharedSchema = [parameter('payload', 'object'), parameter('options', 'object')];
  const sharedOutput = [parameter('result', 'object')];
  const tools = [code('archive', '归档业务附件', sharedSchema, sharedOutput), code('calculate', '计算账期费用', sharedSchema, sharedOutput)];
  const schemaReport = analyzeAgentConflicts({ name: 'Schema测试', systemPrompt: '处理任务', skillIds: [], toolIds: tools.map((tool) => tool.id) }, { skills: [], tools });
  assert.equal(schemaReport.findings[0].kind, 'schema');
  assert.equal(schemaReport.findings[0].severity, 'review', 'identical Schema only warrants review, not a confirmed functional conflict');
  tools[1].inputs = [parameter('amount', 'number')];
  assert.equal(analyzeAgentConflicts({ name: '测试', systemPrompt: '测试', skillIds: [], toolIds: ['archive', 'calculate'] }, { skills: [], tools }).findings.length, 0);
  const missing = analyzeAgentConflicts({ name: '失效测试', systemPrompt: '测试', skillIds: ['missing-skill'], toolIds: ['missing-tool'] }, { skills: [], tools: [] });
  assert.equal(missing.findings.length, 2);
  assert.equal(missing.toolCount, 0);
  const noScope = analyzeAgentConflicts({ name: '空测试', systemPrompt: '', skillIds: [], toolIds: [] }, { skills: [], tools: [] });
  assert(noScope.coverage.some((note) => note.includes('没有有效')));
  assert(noScope.findings.some((finding) => finding.id === 'empty-prompt'));
  assert.throws(() => store.saveAgent({ ...saved, name: '' }, saved.id), /填写/);
  assert.throws(() => store.saveAgent({ ...saved, name: generalAgent.name }, saved.id), /已存在/);
  assert.throws(() => store.saveAgent(saved), /只能编辑/);
  assert.throws(() => store.saveAgent(saved, 'unregistered-agent'), /只能编辑/);
  assert.equal(store.deleteAgent, undefined, 'Agent deletion is not an exposed action');

  setActivePinia(createPinia());
  const synced = useAgentOpsStore();
  const agentsSource = JSON.parse(await readFile(`${root}src/data/agentOpsAgents.json`, 'utf8'));
  const codeSource = JSON.parse(await readFile(`${root}src/data/agentOpsCodeTools.json`, 'utf8'));
  const edited = synced.saveAgent({ ...synced.agents[0], name: '已配置数据员工', systemPrompt: '保留运营指令' }, synced.agents[0].id);
  synced.saveCustomerAgents(customerId, [config(edited.id, ['scan-login-tms'], ['risk-evaluate'])]);
  const beforeSyncCustomers = JSON.stringify(synced.customers);
  const syncDefinitions = structuredClone(agentsSource);
  syncDefinitions[1].name = '工程新版通用对话';
  syncDefinitions.push({ ...agentsSource[2], id: 'engineering-agent', name: '工程新注册 Agent', role: 'custom' });
  await synced.syncAgents(async () => syncDefinitions);
  assert.equal(synced.agents.length, 4);
  assert.equal(JSON.stringify(synced.customers), beforeSyncCustomers, 'registry sync does not assign new Agents or capabilities');
  assert.deepEqual(synced.agents[0], edited, 'sync preserves all explicitly saved Agent settings');
  assert.equal(synced.agents[1].name, '工程新版通用对话', 'unconfigured Agents read the latest engineering defaults');
  assert(synced.agentSync.lastSyncedAt);
  const beforeFailure = JSON.stringify(synced.agents), successTime = synced.agentSync.lastSyncedAt;
  await assert.rejects(synced.syncAgents(async () => { throw new Error('模拟网络失败'); }), /网络失败/);
  await assert.rejects(synced.syncAgents(async () => [...syncDefinitions, syncDefinitions[0]]), /格式/);
  assert.equal(JSON.stringify(synced.agents), beforeFailure);
  assert.equal(synced.agentSync.lastSyncedAt, successTime, 'failed sync does not change last successful time');
  assert.equal(synced.agentSync.busy, false);
  let finishSync;
  const pending = synced.syncAgents(() => new Promise((resolve) => { finishSync = resolve; }));
  assert(synced.agentSync.busy);
  await synced.syncAgents(async () => { assert.fail('duplicate sync must not request twice'); });
  finishSync(agentsSource);
  await pending;
  assert.equal(synced.agents.length, 3, 'only the engineering catalog may remove Agents');
  assert.equal(synced.agentSync.error, '');

  const httpConfig = { name: '测试 HTTP 服务', description: '连接配置验证', transport: 'Streamable HTTP', endpoint: 'https://mcp.example.com/mcp', bearerTokenEnvVar: 'MCP_TEST_TOKEN', headers: [{ key: 'X-Region', value: 'east' }], envHeaders: [{ key: 'X-Api-Key', value: 'MCP_TEST_KEY' }], args: [], envVars: [], timeout: 30 };
  const created = synced.saveMcp(httpConfig);
  assert.equal(created.discovery, 'pending');
  assert.deepEqual(created.methods, []);
  assert(synced.getToolLoading(created.id).unloaded);
  httpConfig.headers[0].value = 'west';
  assert.equal(created.headers[0].value, 'east', 'MCP draft rows are detached on save');
  const skillBinding = synced.skills[0];
  skillBinding.privateToolIds.push(created.id);
  synced.saveCustomerAgents(otherCustomerId, [config(generalAgent.id, [], [created.id])]);
  const agentBinding = synced.resolveCustomerAgent(otherCustomerId, generalAgent.id);
  const pendingReport = synced.detectCustomerAgentConflicts(otherCustomerId, generalAgent.id);
  synced.saveDataEmployeeSkill({ ...synced.dataEmployeeSkills[0], privateToolIds: [created.id] });
  assert(pendingReport.findings.some((finding) => finding.id === `undiscovered-mcp-${created.id}`), 'missing MCP discovery is not a clean conflict result');
  const changed = synced.saveMcp({ ...created, name: 'HTTP 服务已更新', endpoint: 'https://updated.example.com/mcp' }, created.id);
  assert.equal(changed.id, created.id);
  assert(synced.getToolLoading(created.id).direct && synced.getToolLoading(created.id).private);
  assert(agentBinding.toolIds.includes(created.id));
  assert.notEqual(pendingReport.fingerprint, agentConfigurationFingerprint(agentBinding, { skills: synced.agentCallableSkills, tools: synced.tools }));
  const vehicle = synced.tools.find((tool) => tool.id === 'vehicle-mcp');
  const renamedVehicle = synced.saveMcp({ ...vehicle, name: '车辆服务新名称' }, vehicle.id);
  assert.equal(renamedVehicle.methods.length, 3, 'metadata-only changes retain method definitions');
  const reconnectedVehicle = synced.saveMcp({ ...renamedVehicle, endpoint: 'https://other.example.com/mcp' }, vehicle.id);
  assert.equal(reconnectedVehicle.methods.length, 0, 'changed connections must not advertise methods from the old service');
  assert.throws(() => synced.saveMcp({ ...httpConfig, endpoint: 'file:///etc/hosts' }), /HTTP/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, endpoint: 'https://user:pass@example.com' }), /认证信息/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, headers: [{ key: 'X-Region', value: '' }] }), /必须填写/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, bearerTokenEnvVar: 'bad-variable' }), /变量名称/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, envHeaders: [{ key: 'X-Test', value: 'not a name' }] }), /变量名称/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, headers: [{ key: 'X-Api-Key', value: 'value' }] }), /只能配置一次/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, headers: [{ key: 'Authorization', value: 'value' }] }), /重复配置/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, timeout: 0 }), /超时/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, name: changed.name }), /已存在/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, transport: 'stdio', endpoint: 'npx' }, created.id), /不能切换/);
  assert.throws(() => synced.saveMcp(httpConfig, 'risk-evaluate'), /代码工具不能/);
  assert.throws(() => synced.deleteMcp('risk-evaluate'), /代码工具不能/);
  const stdio = synced.saveMcp({ ...httpConfig, name: '测试 STDIO 服务', transport: 'stdio', endpoint: 'npx', args: ['-y', '@example/mcp', '--name=two words'], envVars: [{ key: 'MCP_MODE', value: 'demo' }] });
  assert.equal(stdio.args[2], '--name=two words');
  assert.deepEqual(stdio.headers, []);
  assert.equal(stdio.bearerTokenEnvVar, '');
  assert.deepEqual(stdio.envVars, [{ key: 'MCP_MODE', value: 'demo' }]);

  const codeDefinitions = structuredClone(codeSource);
  codeDefinitions.find((tool) => tool.id === 'risk-evaluate').description = '工程新版风险说明';
  codeDefinitions.push({ ...codeSource[0], id: 'new-code-tool', name: '工程新增工具' });
  const mcpSnapshot = JSON.stringify(synced.tools.filter((tool) => tool.kind === 'mcp'));
  await synced.syncCodeTools(async () => codeDefinitions);
  assert.equal(synced.tools.find((tool) => tool.id === 'risk-evaluate').description, '工程新版风险说明');
  assert.equal(synced.tools.filter((tool) => tool.kind === 'code').length, 11);
  assert.equal(JSON.stringify(synced.tools.filter((tool) => tool.kind === 'mcp')), mcpSnapshot);
  assert(synced.customerAgentsForTool('risk-evaluate').some((usage) => usage.customerId === customerId && usage.agentId === edited.id));
  assert(synced.skills.some((skill) => skill.privateToolIds.includes('risk-evaluate')));
  assert(synced.getToolLoading('new-code-tool').unloaded);
  const beforeCodeFailure = JSON.stringify(synced.tools), codeSuccessTime = synced.codeToolSync.lastSyncedAt;
  await assert.rejects(synced.syncCodeTools(async () => [{ ...codeSource[0], inputs: 'bad schema' }]), /格式/);
  await assert.rejects(synced.syncCodeTools(async () => { throw new Error('请求失败'); }), /请求失败/);
  await assert.rejects(synced.syncCodeTools(async () => [{ ...codeSource[0], id: created.id }]), /标识.*冲突/);
  assert.equal(JSON.stringify(synced.tools), beforeCodeFailure);
  assert.equal(synced.codeToolSync.lastSyncedAt, codeSuccessTime);
  await synced.syncCodeTools(async () => codeSource.filter((tool) => tool.id !== 'risk-evaluate'));
  assert(synced.customerAgentsForTool('risk-evaluate').some((usage) => usage.customerId === customerId && usage.agentId === edited.id), 'removed engineering tools retain visible invalid references until reviewed');
  assert(synced.detectCustomerAgentConflicts(customerId, edited.id).findings.some((finding) => finding.id === 'missing-tool-risk-evaluate'));
  await synced.syncCodeTools(async () => codeSource);
  assert.equal(synced.codeToolSync.error, '');
  assert(synced.mcpUsage(created.id).skills.some((skill) => skill.id === skillBinding.id));
  assert(synced.mcpUsage(created.id).agents.some((agent) => agent.customerId === otherCustomerId && agent.agentId === generalAgent.id));
  synced.deleteMcp(created.id);
  assert(!synced.tools.some((tool) => tool.id === created.id));
  assert(synced.skills.every((skill) => !skill.privateToolIds.includes(created.id)));
  assert(synced.customers.every(customer => customer.agentConfigs.every(binding => !binding.toolIds.includes(created.id))));
  assert(synced.dataEmployeeSkills.every(skill => !skill.privateToolIds.includes(created.id)));
  await synced.syncAgents(async () => agentsSource);
  assert(!synced.resolveCustomerAgent(otherCustomerId, generalAgent.id).toolIds.includes(created.id));
  assert(synced.tools.some((tool) => tool.id === stdio.id), 'deletion does not affect another service');
  console.log('Passed: Customer-Agent isolation, group snapshot selection, private Tool independence, shared prompts and scoped conflict detection; engineering sync and failure rollback; MCP HTTP/STDIO CRUD, validation and reference cleanup.');
} finally {
  await server.close();
}
