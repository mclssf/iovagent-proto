import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { readFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const { useAgentOpsStore } = await server.ssrLoadModule('/src/pinia/agentOps.ts');
  const { analyzeAgentConflicts, agentConfigurationFingerprint, resolveAgentTools } = await server.ssrLoadModule('/src/views/AgentOps/agentConflicts.ts');
  setActivePinia(createPinia());
  const store = useAgentOpsStore();
  const catalog = () => ({ skills: store.agentCallableSkills, tools: store.tools });
  assert.deepEqual(store.agents.map((agent) => agent.name), ['数据员工 Agent', '通用对话 Agent', '项目对话 Agent']);
  const dataAgent = store.agents.find((agent) => agent.role === 'data-employee');
  const generalAgent = store.agents.find((agent) => agent.role === 'general-chat');
  const projectAgent = store.agents.find((agent) => agent.role === 'project-chat');
  assert.equal(dataAgent.skillIds.length, 5);
  assert.deepEqual(dataAgent.skillIds, store.dataEmployeeSkills.map((skill) => skill.id), 'all data employee Skills are initially loaded');
  assert(store.availableSkillsForAgent(dataAgent.id).every((skill) => skill.source === 'data-employee'));
  assert(store.availableSkillsForAgent(generalAgent.id).every((skill) => skill.source === 'common'));
  assert(store.availableSkillsForAgent(projectAgent.id).every((skill) => skill.source === 'common'));
  assert(!store.skills.some((skill) => dataAgent.skillIds.includes(skill.id)), 'data acquisition Skills are not duplicated in common Skill management');
  const dataReport = store.detectAgentConflicts(dataAgent.id);
  assert.equal(dataReport.skillCount, 5);
  assert(!dataReport.findings.some((finding) => finding.id.startsWith('missing-skill')));
  const employee = store.dataEmployeeSkills[0];
  const commonBeforeDataEdit = JSON.stringify(store.skills);
  store.saveDataEmployeeSkill({ ...employee, name: '金隅水泥采集 Skill', loginUrl: 'https://jinyu.example.com/login', skillContent: '# 新版采集指引', skillVersion: 'v2.0' });
  const mappedSkill = store.agentCallableSkills.find((skill) => skill.id === employee.id);
  assert.equal(mappedSkill.name, '金隅水泥采集 Skill');
  assert.equal(mappedSkill.content, '# 新版采集指引');
  assert.equal(mappedSkill.sourceConfig.loginUrl, 'https://jinyu.example.com/login');
  assert.notEqual(dataReport.fingerprint, agentConfigurationFingerprint(dataAgent, catalog()), 'data Skill changes invalidate conflict reports');
  assert.equal(JSON.stringify(store.skills), commonBeforeDataEdit);
  const generalIds = [...generalAgent.skillIds], projectIds = [...projectAgent.skillIds];
  const added = { ...employee, id: 'new-data-source', name: '新增数据来源', enterpriseIds: ['ent-demo'] };
  store.saveDataEmployeeSkill(added);
  added.enterpriseIds.push('ent-jinyu');
  assert(dataAgent.skillIds.includes(added.id), 'new data employee Skill joins the data Agent loading list');
  assert.deepEqual(store.dataEmployeeSkills.find((skill) => skill.id === added.id).enterpriseIds, ['ent-demo']);
  assert.deepEqual(generalAgent.skillIds, generalIds);
  assert.deepEqual(projectAgent.skillIds, projectIds);
  const dataWithoutOne = store.saveAgent({ ...dataAgent, skillIds: dataAgent.skillIds.filter((id) => id !== employee.id) }, dataAgent.id);
  assert.equal(dataWithoutOne.role, 'data-employee', 'editing retains the Agent role');
  assert(store.dataEmployeeSkills.some((skill) => skill.id === employee.id), 'unloading a Skill does not delete its source configuration');
  assert(store.availableSkillsForAgent(dataAgent.id).some((skill) => skill.id === employee.id), 'unloaded data Skill remains available for selection');
  store.saveDataEmployeeSkill({ ...employee, description: '修改后仍保留独立加载选择' });
  assert(!dataWithoutOne.skillIds.includes(employee.id), 'updating a Skill does not re-enable an explicitly unloaded Skill');

  const transit = store.saveAgent({ name: '在途测试', systemPrompt: '测试在途能力', skillIds: ['route-risk-expert', 'vehicle-location-query', 'vehicle-trace-query'], toolIds: ['vehicle-mcp', 'risk-evaluate'] }, projectAgent.id);
  const operations = store.saveAgent({ name: '运营测试', systemPrompt: '测试运营能力', skillIds: ['operations-logistics-sheet', 'operations-sms-notification'], toolIds: ['datetime-format'] }, generalAgent.id);
  const capacity = { name: '运力测试', systemPrompt: '测试运力能力', skillIds: ['capacity-find-carrier', 'capacity-quote-query', 'capacity-private-fleet'], toolIds: [] };
  assert.equal(store.globalToolIds, undefined, 'global loading state is no longer exposed');
  assert.equal(store.setToolGlobalLoading, undefined, 'global loading can no longer be configured');
  const transitReport = store.detectAgentConflicts(transit.id);
  assert.equal(transitReport.findings.filter((finding) => finding.kind === 'duplicate').length, 2);
  assert(transitReport.findings.find((finding) => finding.id === 'duplicate-vehicle-mcp').paths.length === 4, 'all private and direct paths are included');
  assert.equal(store.detectAgentConflicts(operations.id).findings.length, 0, 'different functions are not treated as ambiguous');
  assert.equal(analyzeAgentConflicts(capacity, catalog()).findings.length, 0, 'sharing a dependency alone is not a conflict');
  assert(transitReport.coverage.some((note) => note.includes('未声明') && note.includes('MCP')));

  const originalSkills = JSON.stringify(store.skills);
  const originalTools = JSON.stringify(store.tools);
  const draft = { name: '边界测试 Agent', systemPrompt: '测试 Agent 的能力调用。', skillIds: ['route-risk-expert'], toolIds: ['risk-evaluate'] };
  const saved = store.saveAgent(draft, generalAgent.id);
  draft.skillIds.push('operations-sms-notification');
  assert.deepEqual(saved.skillIds, ['route-risk-expert'], 'saved arrays are detached from the editor draft');
  assert.equal(JSON.stringify(store.skills), originalSkills, 'Agent edits preserve Skill private bindings');
  assert.equal(JSON.stringify(store.tools), originalTools, 'Agent edits preserve engineering-owned definitions');
  const otherAgent = store.agents.find((agent) => agent.id === dataAgent.id);
  const isolatedAgent = { ...otherAgent, skillIds: [], toolIds: [] };
  assert.equal(resolveAgentTools(isolatedAgent, catalog()).length, 0, 'another Agent direct assignment never leaks into this Agent');
  assert.equal(resolveAgentTools(isolatedAgent, { ...catalog(), globalToolIds: ['risk-evaluate'] }).length, 0, 'obsolete global state does not grant access');
  assert(store.agentsForTool('risk-evaluate').some((agent) => agent.id === saved.id));
  const directReport = store.detectAgentConflicts(saved.id);
  assert.equal(directReport.findings.find((finding) => finding.id === 'duplicate-risk-evaluate').paths.length, 2, 'conflict detection only includes direct and private paths');

  const noDirect = store.saveAgent({ ...saved, toolIds: [] }, saved.id);
  assert.notEqual(directReport.fingerprint, agentConfigurationFingerprint(noDirect, catalog()), 'removing direct loading invalidates the conflict report');
  const privateReport = store.detectAgentConflicts(noDirect.id);
  assert.equal(privateReport.findings.length, 0, 'a Skill with its own private tool is an ordinary dependency');
  assert(resolveAgentTools(noDirect, catalog()).some((usage) => usage.id === 'risk-evaluate'));
  const skill = store.skills.find((item) => item.id === 'route-risk-expert');
  skill.privateToolIds = skill.privateToolIds.filter((id) => id !== 'risk-evaluate');
  assert.notEqual(privateReport.fingerprint, agentConfigurationFingerprint(noDirect, catalog()), 'Skill private binding edits invalidate old reports');
  assert.deepEqual(noDirect.toolIds, [], 'Skill edits do not rewrite Agent direct assignments');
  store.saveAgent({ ...noDirect, toolIds: ['risk-evaluate'] }, noDirect.id);
  const latestAgent = store.agents.find((item) => item.id === noDirect.id);
  const ambiguity = store.detectAgentConflicts(latestAgent.id);
  assert(ambiguity.findings.some((finding) => finding.kind === 'intent' && finding.evidence.some((evidence) => evidence.includes('评估在途风险'))), 'different identities with overlapping intent yield explainable ambiguity');
  skill.enabled = false;
  const disabled = store.detectAgentConflicts(latestAgent.id);
  assert(disabled.findings.some((finding) => finding.id === 'disabled-skill-route-risk-expert'));
  assert(!resolveAgentTools(latestAgent, catalog()).some((usage) => usage.id === 'vehicle-mcp'), 'disabled Skill dependencies are excluded');
  assert(resolveAgentTools(latestAgent, catalog()).some((usage) => usage.id === 'risk-evaluate'), 'disabled Skill does not disable an independently loaded tool');
  const beforePromptEdit = agentConfigurationFingerprint(latestAgent, catalog());
  latestAgent.systemPrompt += '\n新路由约定';
  assert.notEqual(beforePromptEdit, agentConfigurationFingerprint(latestAgent, catalog()));

  const parameter = (name, type) => ({ name, type, required: true, description: name });
  const code = (id, description, inputs, outputs) => ({ id, name: id, description, kind: 'code', inputs, outputs, runtime: 'Python 3', entrypoint: 'tools/test.py:run', updatedAt: '' });
  const sharedSchema = [parameter('payload', 'object'), parameter('options', 'object')];
  const sharedOutput = [parameter('result', 'object')];
  const tools = [code('archive', '归档业务附件', sharedSchema, sharedOutput), code('calculate', '计算账期费用', sharedSchema, sharedOutput)];
  const schemaReport = analyzeAgentConflicts({ name: 'Schema测试', systemPrompt: '处理任务', skillIds: [], toolIds: tools.map((tool) => tool.id) }, { skills: [], tools });
  assert.equal(schemaReport.findings[0].kind, 'schema');
  assert.equal(schemaReport.findings[0].severity, 'review', 'identical Schema only warrants review, not a confirmed functional conflict');
  tools[1].inputs = [parameter('amount', 'number')];
  assert.equal(analyzeAgentConflicts({ name: '测试', systemPrompt: '测试', skillIds: [], toolIds: ['archive', 'calculate'] }, { skills: [], tools }).findings.length, 0);
  const missing = analyzeAgentConflicts({ name: '失效测试', systemPrompt: '测试', skillIds: ['missing-skill'], toolIds: ['missing-tool'] }, { skills: [], tools: [] });
  assert.equal(missing.findings.length, 2);
  assert.equal(missing.toolCount, 0);
  const noScope = analyzeAgentConflicts({ name: '空测试', systemPrompt: '', skillIds: [], toolIds: [] }, { skills: [], tools: [] });
  assert(noScope.coverage.some((note) => note.includes('没有有效')));
  assert(noScope.findings.some((finding) => finding.id === 'empty-prompt'));
  assert.throws(() => store.saveAgent({ ...saved, name: '' }, saved.id), /填写/);
  assert.throws(() => store.saveAgent({ ...saved, name: transit.name }, saved.id), /已存在/);
  assert.throws(() => store.saveAgent(draft), /只能编辑/);
  assert.throws(() => store.saveAgent(draft, 'unregistered-agent'), /只能编辑/);
  assert.equal(store.deleteAgent, undefined, 'Agent deletion is not an exposed action');

  setActivePinia(createPinia());
  const synced = useAgentOpsStore();
  const agentsSource = JSON.parse(await readFile(`${root}src/data/agentOpsAgents.json`, 'utf8'));
  const codeSource = JSON.parse(await readFile(`${root}src/data/agentOpsCodeTools.json`, 'utf8'));
  const edited = synced.saveAgent({ ...synced.agents[0], name: '已配置数据员工', systemPrompt: '保留运营指令', skillIds: ['scan-login-tms'], toolIds: ['risk-evaluate'] }, synced.agents[0].id);
  const syncDefinitions = structuredClone(agentsSource);
  syncDefinitions[1].name = '工程新版通用对话';
  syncDefinitions.push({ ...agentsSource[2], id: 'engineering-agent', name: '工程新注册 Agent', role: 'custom' });
  await synced.syncAgents(async () => syncDefinitions);
  assert.equal(synced.agents.length, 4);
  assert.deepEqual(synced.agents[0], edited, 'sync preserves all explicitly saved Agent settings');
  assert.equal(synced.agents[1].name, '工程新版通用对话', 'unconfigured Agents read the latest engineering defaults');
  assert(synced.agentSync.lastSyncedAt);
  const beforeFailure = JSON.stringify(synced.agents), successTime = synced.agentSync.lastSyncedAt;
  await assert.rejects(synced.syncAgents(async () => { throw new Error('模拟网络失败'); }), /网络失败/);
  await assert.rejects(synced.syncAgents(async () => [...syncDefinitions, syncDefinitions[0]]), /格式/);
  assert.equal(JSON.stringify(synced.agents), beforeFailure);
  assert.equal(synced.agentSync.lastSyncedAt, successTime, 'failed sync does not change last successful time');
  assert.equal(synced.agentSync.busy, false);
  let finishSync;
  const pending = synced.syncAgents(() => new Promise((resolve) => { finishSync = resolve; }));
  assert(synced.agentSync.busy);
  await synced.syncAgents(async () => { assert.fail('duplicate sync must not request twice'); });
  finishSync(agentsSource);
  await pending;
  assert.equal(synced.agents.length, 3, 'only the engineering catalog may remove Agents');
  assert.equal(synced.agentSync.error, '');

  const httpConfig = { name: '测试 HTTP 服务', description: '连接配置验证', transport: 'Streamable HTTP', endpoint: 'https://mcp.example.com/mcp', bearerTokenEnvVar: 'MCP_TEST_TOKEN', headers: [{ key: 'X-Region', value: 'east' }], envHeaders: [{ key: 'X-Api-Key', value: 'MCP_TEST_KEY' }], args: [], envVars: [], timeout: 30 };
  const created = synced.saveMcp(httpConfig);
  assert.equal(created.discovery, 'pending');
  assert.deepEqual(created.methods, []);
  assert(synced.getToolLoading(created.id).unloaded);
  httpConfig.headers[0].value = 'west';
  assert.equal(created.headers[0].value, 'east', 'MCP draft rows are detached on save');
  const skillBinding = synced.skills[0];
  skillBinding.privateToolIds.push(created.id);
  const agentBinding = synced.saveAgent({ ...synced.agents[1], toolIds: [created.id] }, synced.agents[1].id);
  const pendingReport = synced.detectAgentConflicts(agentBinding.id);
  assert(pendingReport.findings.some((finding) => finding.id === `undiscovered-mcp-${created.id}`), 'missing MCP discovery is not a clean conflict result');
  const changed = synced.saveMcp({ ...created, name: 'HTTP 服务已更新', endpoint: 'https://updated.example.com/mcp' }, created.id);
  assert.equal(changed.id, created.id);
  assert(synced.getToolLoading(created.id).direct && synced.getToolLoading(created.id).private);
  assert(agentBinding.toolIds.includes(created.id));
  assert.notEqual(pendingReport.fingerprint, agentConfigurationFingerprint(agentBinding, { skills: synced.agentCallableSkills, tools: synced.tools }));
  const vehicle = synced.tools.find((tool) => tool.id === 'vehicle-mcp');
  const renamedVehicle = synced.saveMcp({ ...vehicle, name: '车辆服务新名称' }, vehicle.id);
  assert.equal(renamedVehicle.methods.length, 3, 'metadata-only changes retain method definitions');
  const reconnectedVehicle = synced.saveMcp({ ...renamedVehicle, endpoint: 'https://other.example.com/mcp' }, vehicle.id);
  assert.equal(reconnectedVehicle.methods.length, 0, 'changed connections must not advertise methods from the old service');
  assert.throws(() => synced.saveMcp({ ...httpConfig, endpoint: 'file:///etc/hosts' }), /HTTP/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, endpoint: 'https://user:pass@example.com' }), /认证信息/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, headers: [{ key: 'X-Region', value: '' }] }), /必须填写/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, bearerTokenEnvVar: 'bad-variable' }), /变量名称/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, envHeaders: [{ key: 'X-Test', value: 'not a name' }] }), /变量名称/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, headers: [{ key: 'X-Api-Key', value: 'value' }] }), /只能配置一次/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, headers: [{ key: 'Authorization', value: 'value' }] }), /重复配置/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, timeout: 0 }), /超时/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, name: changed.name }), /已存在/);
  assert.throws(() => synced.saveMcp({ ...httpConfig, transport: 'stdio', endpoint: 'npx' }, created.id), /不能切换/);
  assert.throws(() => synced.saveMcp(httpConfig, 'risk-evaluate'), /代码工具不能/);
  assert.throws(() => synced.deleteMcp('risk-evaluate'), /代码工具不能/);
  const stdio = synced.saveMcp({ ...httpConfig, name: '测试 STDIO 服务', transport: 'stdio', endpoint: 'npx', args: ['-y', '@example/mcp', '--name=two words'], envVars: [{ key: 'MCP_MODE', value: 'demo' }] });
  assert.equal(stdio.args[2], '--name=two words');
  assert.deepEqual(stdio.headers, []);
  assert.equal(stdio.bearerTokenEnvVar, '');
  assert.deepEqual(stdio.envVars, [{ key: 'MCP_MODE', value: 'demo' }]);

  const codeDefinitions = structuredClone(codeSource);
  codeDefinitions.find((tool) => tool.id === 'risk-evaluate').description = '工程新版风险说明';
  codeDefinitions.push({ ...codeSource[0], id: 'new-code-tool', name: '工程新增工具' });
  const mcpSnapshot = JSON.stringify(synced.tools.filter((tool) => tool.kind === 'mcp'));
  await synced.syncCodeTools(async () => codeDefinitions);
  assert.equal(synced.tools.find((tool) => tool.id === 'risk-evaluate').description, '工程新版风险说明');
  assert.equal(synced.tools.filter((tool) => tool.kind === 'code').length, 11);
  assert.equal(JSON.stringify(synced.tools.filter((tool) => tool.kind === 'mcp')), mcpSnapshot);
  assert(synced.agentsForTool('risk-evaluate').some((agent) => agent.id === edited.id));
  assert(synced.skills.some((skill) => skill.privateToolIds.includes('risk-evaluate')));
  assert(synced.getToolLoading('new-code-tool').unloaded);
  const beforeCodeFailure = JSON.stringify(synced.tools), codeSuccessTime = synced.codeToolSync.lastSyncedAt;
  await assert.rejects(synced.syncCodeTools(async () => [{ ...codeSource[0], inputs: 'bad schema' }]), /格式/);
  await assert.rejects(synced.syncCodeTools(async () => { throw new Error('请求失败'); }), /请求失败/);
  await assert.rejects(synced.syncCodeTools(async () => [{ ...codeSource[0], id: created.id }]), /标识.*冲突/);
  assert.equal(JSON.stringify(synced.tools), beforeCodeFailure);
  assert.equal(synced.codeToolSync.lastSyncedAt, codeSuccessTime);
  await synced.syncCodeTools(async () => codeSource.filter((tool) => tool.id !== 'risk-evaluate'));
  assert(synced.agentsForTool('risk-evaluate').some((agent) => agent.id === edited.id), 'removed engineering tools retain visible invalid references until reviewed');
  assert(synced.detectAgentConflicts(edited.id).findings.some((finding) => finding.id === 'missing-tool-risk-evaluate'));
  await synced.syncCodeTools(async () => codeSource);
  assert.equal(synced.codeToolSync.error, '');
  assert(synced.mcpUsage(created.id).skills.some((skill) => skill.id === skillBinding.id));
  assert(synced.mcpUsage(created.id).agents.some((agent) => agent.id === agentBinding.id));
  synced.deleteMcp(created.id);
  assert(!synced.tools.some((tool) => tool.id === created.id));
  assert(synced.skills.every((skill) => !skill.privateToolIds.includes(created.id)));
  assert(synced.agents.every((agent) => !agent.toolIds.includes(created.id)));
  await synced.syncAgents(async () => agentsSource);
  assert(!synced.agents.find((agent) => agent.id === agentBinding.id).toolIds.includes(created.id));
  assert(synced.tools.some((tool) => tool.id === stdio.id), 'deletion does not affect another service');
  console.log('Passed: Agent relationships and conflict detection; engineering sync and failure rollback; MCP HTTP/STDIO CRUD, validation and reference cleanup.');
} finally {
  await server.close();
}
