import assert from 'node:assert/strict';

// Run against a local dev server with Playwright available to Node.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || undefined, headless: true });
const root = process.env.TEST_BASE_URL || 'http://127.0.0.1:5173';
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const chat = await context.newPage(), ops = await context.newPage();
  const errors = [];
  for (const page of [chat, ops]) { page.setDefaultTimeout(6000); page.on('pageerror', e => errors.push(e.message)); }
  const input = chat.getByPlaceholder('发消息...');
  const button = (page, name) => page.getByRole('button', { name, exact: true });
  const open = () => chat.locator('.summon-trigger').click();
  const pick = async name => {
    const d = chat.getByRole('dialog', { name: '数字人技能' });
    const action = button(d, '召唤 ' + name);
    const card = action.locator('xpath=ancestor::article');
    const [a, c] = await Promise.all([action.boundingBox(), card.boundingBox()]);
    assert(a && c && a.y < c.y + 22 && c.x + c.width - a.x - a.width < 22, 'top-right action');
    await action.click();
    await d.waitFor({ state: 'hidden' });
  };
  await chat.goto(root + '/index/agent');
  await button(chat, '新对话').click();
  await button(chat, '数字人技能').first().click();
  await pick('物流表格');
  const initial = await input.inputValue();
  assert(initial.includes('运单'));
  assert.equal(await chat.locator('.agent-message.is-user').count(), 0);
  await open(); await pick('证照识别');
  assert.notEqual(await input.inputValue(), initial);
  await input.fill('请整理运输台账');
  await chat.locator('input[type=file]').setInputFiles({ name: '委托.txt', mimeType: 'text/plain', buffer: Buffer.from('委托') });
  await open(); await pick('物流表格');
  assert.equal(await input.inputValue(), '请整理运输台账');
  await open(); await button(chat, '已召唤 物流表格').click();
  assert.equal(await input.inputValue(), '请整理运输台账');
  await button(chat, '查看推荐提示词').click();
  await button(chat.getByRole('dialog'), '取消').click();
  assert.equal(await input.inputValue(), '请整理运输台账');
  await button(chat, '查看推荐提示词').click(); await button(chat, '替换当前输入').click();
  assert.equal(await input.inputValue(), initial);
  await button(chat, '取消召唤').click();
  assert.equal(await input.inputValue(), initial);
  assert.equal(await chat.getByRole('dialog').count(), 0);
  assert.equal(await button(chat, '删除文件 委托.txt').count(), 1);
  await open(); await pick('物流表格');
  await input.fill('按委托整理');
  await button(chat, '发送').click();
  await chat.getByText('本次召唤：物流表格', { exact: true }).waitFor();
  assert.equal(await input.inputValue(), '');
  assert.equal(await button(chat, '取消召唤').count(), 0);
  assert.equal(await button(chat, '删除文件 委托.txt').count(), 0);
  await open(); await pick('物流表格'); await input.fill('客户原话，不覆盖');

  await ops.goto(root + '/agent-ops');
  await ops.getByRole('button', { name: /Skill 管理/ }).first().click();
  const row = ops.getByRole('row').filter({ hasText: 'operations-logistics-sheet' });
  await button(row, '配置').click();
  const template = '请整理运输明细。\n按承运商分组。';
  await ops.getByRole('textbox', { name: '默认推荐提示词' }).fill(template);
  await button(ops.getByRole('dialog'), '保存').click();
  assert.equal(await input.inputValue(), '客户原话，不覆盖');
  await button(chat, '取消召唤').click(); await input.fill('');
  await open(); await pick('物流表格');
  assert.equal(await input.inputValue(), template, 'new summon uses the saved multiline prompt');
  await input.fill('保留这份草稿');
  await ops.getByRole('button', { name: /客户 Agent 配置/ }).first().click();
  await button(ops, '配置 华东物流事业部').click();
  await ops.getByRole('button', { name: /通用对话 Agent/ }).first().click();
  await ops.getByRole('radio', { name: '自定义配置' }).check();
  await button(ops, '移除 Skill 物流表格').click();
  await button(ops, '保存配置').click();
  await chat.getByText('该技能已不可用，输入内容已保留。请重新选择技能，或按普通对话发送。').waitFor();
  assert.equal(await input.inputValue(), '保留这份草稿');
  await open(); assert.equal(await button(chat, '召唤 物流表格').count(), 0);
  await chat.getByRole('searchbox').fill('不存在的技能');
  await chat.getByText('没有匹配的技能').waitFor();
  await chat.getByRole('searchbox').fill('证照');
  await pick('证照识别');
  await chat.setViewportSize({ width: 390, height: 844 });
  const [chip, model, send] = await Promise.all([chat.locator('.summon-tool').boundingBox(), chat.getByRole('combobox', { name: '内置模型' }).boundingBox(), button(chat, '发送').boundingBox()]);
  assert(chip && model && send && chip.x >= 0 && chip.x + chip.width <= send.x && (model.x + model.width <= chip.x || model.y + model.height <= chip.y));
  await open();
  await button(chat, '已召唤 证照识别').waitFor();
  const smallCard = await chat.locator('.summon-card').first().boundingBox();
  assert(smallCard && smallCard.x >= 0 && smallCard.x + smallCard.width <= 390);
  await button(chat, '已召唤 证照识别').click();
  await chat.setViewportSize({ width: 1440, height: 900 });
  await button(chat, '下载').click();
  await button(chat, '数字人技能').click();
  await chat.getByLabel('目标智能体').selectOption('data-employee-agent');
  await pick('表格运单');
  assert.equal(await input.inputValue(), '');
  await chat.getByText('请描述希望该技能完成的任务，可补充车牌、时间、地点或上传文件。').waitFor();
  await button(chat, '对第一项对话的总结').click();
  assert.equal(await input.inputValue(), '保留这份草稿');
  assert.equal(await chat.locator('.summon-trigger').innerText(), '证照识别');

  const key = 'iovagent-agent-loading-v1:customer:ent-east';
  const saved = await chat.evaluate(k => localStorage.getItem(k), key);
  await chat.evaluate(k => localStorage.setItem(k, '{'), key);
  await open();
  await chat.getByText('技能配置读取失败，请重试。', { exact: false }).waitFor();
  await chat.evaluate(([k, v]) => localStorage.setItem(k, v), [key, saved]);
  await button(chat, '重试').click();
  await button(chat, '已召唤 证照识别').click();
  // A same-tab write has no storage notification. Submission must still recheck the grant.
  await chat.evaluate(k => {
    const rows = JSON.parse(localStorage.getItem(k));
    rows.find(r => r.agentId === 'general-chat-agent').skillIds = [];
    localStorage.setItem(k, JSON.stringify(rows));
  }, key);
  const messageCount = await chat.locator('.agent-message.is-user').count();
  await button(chat, '发送').click();
  await chat.locator('.skill-input-tip').filter({ hasText: '该技能已不可用' }).waitFor();
  assert.equal(await chat.locator('.agent-message.is-user').count(), messageCount);
  assert.equal(await input.inputValue(), '保留这份草稿');
  await open(); await chat.getByText('当前智能体暂无可用技能，请联系管理员配置。').waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: both entry points; upper-right actions; one-skill drafts, replacement, cancellation and files; message receipt; real ops edit/unload across tabs; search and narrow toolbar.');
} finally { await browser.close(); }
