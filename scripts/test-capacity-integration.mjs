import { ElMessage } from 'element-plus';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';
const root = fileURLToPath(new URL('../', import.meta.url));
const server = await createServer({ configFile: false, root, resolve: { alias: { '@': `${root}src` } }, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
const originalSuccess = ElMessage.success;
ElMessage.success = () => ({ close() {} });
try {
  setActivePinia(createPinia());
  const { useAgentOpsStore } = await server.ssrLoadModule('/src/pinia/agentOps.ts');
  const { agentWorkData } = await server.ssrLoadModule('/src/pinia/agentWork.ts');
  const ops = useAgentOpsStore(), work = agentWorkData();
  const oldIds = ['capacity-find-carrier', 'capacity-quote-query', 'capacity-cargo-search'];
  const newIds = ['capacity-cargo-publish', 'capacity-quote-collection', 'capacity-cargo-normalization'];
  assert(oldIds.every(id => !ops.skills.some(skill => skill.id === id)));
  assert(newIds.every(id => ops.skills.some(skill => skill.id === id && skill.enabled)));
  const agent = ops.agents.find(item => item.role === 'project-chat');
  ops.saveAgent(agent, agent.id, { skillIds: [...oldIds, newIds[0]], toolIds: [] });
  assert.deepEqual(ops.agentDefaultConfig(agent.id).skillIds, newIds, 'default grants migrate and deduplicate');
  ops.saveCustomerAgents('ent-east', [{ agentId: agent.id, mode: 'custom', skillIds: oldIds, toolIds: ['capacity-mcp'], systemPrompt: '保留客户指令' }]);
  const migrated = ops.resolveCustomerAgent('ent-east', agent.id);
  assert.deepEqual(migrated.skillIds, newIds);
  assert.equal(migrated.systemPrompt, '保留客户指令');
  assert.deepEqual(migrated.toolIds, ['capacity-mcp']);
  assert.deepEqual(ops.customers.find(item => item.id === 'ent-east').agentConfigs.find(item => item.agentId === agent.id).skillIds, newIds);
  assert(ops.skills.filter(skill => newIds.includes(skill.id)).every(skill => skill.privateToolIds.includes('capacity-mcp')));
  const unrelated = JSON.stringify(ops.resolveCustomerAgent('ent-jinyu', agent.id));
  ops.saveAgent(agent, agent.id, { skillIds: [], toolIds: [] });
  assert.equal(JSON.stringify(ops.resolveCustomerAgent('ent-jinyu', agent.id)), unrelated);
  assert.deepEqual(ops.resolveCustomerAgent('ent-east', agent.id).skillIds, newIds, 'custom configuration stays independent');
  work.updateSkillProject('P001', '迁移测试', ['货源发布', '报价抢单', '货源解析'], oldIds);
  assert(newIds.every(id => work.projects.find(project => project.id === 'P001').skillIds.includes(id)));
  work.currentProjectId = 'P001';
  assert.equal(work.cargoSourcesFiltered.length, 4, 'default week includes all seed cargo');
  assert.equal(work.cargoQuotesFiltered.length, 5, 'default week includes all seed feedback');
  for (const cargo of work.cargoSources) {
    const quotes = work.cargoQuotes.filter(item => item.cargoId === cargo.id);
    assert.equal(cargo.quoteCount, quotes.filter(item => item.type !== '电话联系').length);
    assert.equal(cargo.contactCount, quotes.filter(item => item.type === '电话联系').length);
  }
  const quote = work.cargoQuotes.find(item => item.status === '待处理');
  const cargo = work.cargoSources.find(item => item.id === quote.cargoId);
  work.currentProjectId = 'P003';
  work.dispatchQuote(quote.id);
  work.offlineCargo(cargo.id);
  assert.equal(cargo.status, '发布中', 'other projects cannot mutate this cargo');
  assert.equal(quote.status, '待处理');
  work.importCargoFile('test.xlsx');
  assert.equal(work.cargoSources[0].projectId, 'P003', 'imports belong to current project');
  assert.equal(work.cargoSourcesFiltered.length, 1);
  work.currentProjectId = 'P001';
  work.dispatchQuote(quote.id);
  assert.equal(cargo.status, '已派车');
  assert(cargo.platformPublications.every(item => item.status === '已下架'));
  const other = work.cargoQuotes.find(item => item.cargoId === cargo.id && item.id !== quote.id);
  const previous = other.status;
  work.dispatchQuote(other.id);
  assert.equal(other.status, previous, 'cannot dispatch the same cargo twice');
  work.publishCargo(cargo.id);
  assert.equal(cargo.status, '已派车');
  work.quoteStartDate = '2099-01-01';
  work.focusCargoQuotes(cargo.id);
  assert.equal(work.cargoQuotesFiltered.length, 3, 'deep links show related feedback outside the previous date filter');
  console.log('Passed: legacy Skill migration, customer/default isolation, project grants, cargo date filters, counts, import scope and dispatch state.');
} finally { ElMessage.success = originalSuccess; await server.close(); }
