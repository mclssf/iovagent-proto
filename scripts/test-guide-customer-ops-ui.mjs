import assert from 'node:assert/strict';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || undefined, headless: true });
const root = process.env.TEST_BASE_URL || 'http://127.0.0.1:5803';
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const ops = await context.newPage(), chat = await context.newPage();
  const button = (page, name) => page.getByRole('button', { name, exact: true });
  const group = ops.getByRole('group', { name: '运输场景技能' });
  const name = '进场车辆核查';
  const grant = group.getByRole('checkbox', { name, exact: true });
  const summon = button(chat, '召唤 ' + name);
  const picker = chat.getByRole('dialog', { name: '数字人技能' });
  const openPicker = () => chat.locator('.summon-trigger').click();
  const save = () => button(ops, '保存配置').click();
  const openCustomer = () => button(ops, '配置 华东物流事业部').click();
  const errors = [];
  for (const page of [ops, chat]) page.on('pageerror', error => errors.push(error.message));
  await ops.goto(root + '/agent-ops');
  await openCustomer();
  await group.waitFor();
  const checks = group.getByRole('checkbox');
  const names = await checks.evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')));
  assert.equal(new Set(names).size, 8);
  assert.equal(await group.locator('input:checked:disabled').count(), 8);
  await chat.goto(root + '/index/agent');
  await chat.getByRole('button', { name: /^华东运输核查/ }).click();
  await openPicker();
  for (const skill of names) await button(chat, '召唤 ' + skill).waitFor();
  await ops.getByRole('radio', { name: '自定义配置' }).check();
  await grant.uncheck();
  assert(await summon.isVisible(), 'unsaved edits must not change user access');
  await save();
  await summon.waitFor({ state: 'detached' });
  await button(chat, '召唤 装卸图片核验').waitFor();
  await chat.keyboard.press('Escape');
  await picker.waitFor({ state: 'hidden' });
  await button(chat, '新对话').click();
  await openPicker();
  await summon.waitFor(); // The general chat grant is independent of the project grant.
  await chat.keyboard.press('Escape');
  await chat.getByRole('button', { name: /^华东运输核查/ }).click();
  await openPicker();
  assert.equal(await summon.count(), 0);
  await ops.reload();
  await openCustomer();
  await grant.waitFor();
  assert.equal(await grant.isChecked(), false);
  await grant.check();
  await save();
  await summon.waitFor();
  await ops.getByRole('button', { name: /^数据员工 Agent/ }).click();
  assert.equal(await group.count(), 0);
  await button(ops, '返回客户列表').click();
  await ops.getByRole('button', { name: /Skill 管理/ }).first().click();
  await ops.getByLabel('筛选 Skill 分组').selectOption('运输场景技能');
  assert.equal(await ops.locator('tbody:visible tr').count(), 8);
  const row = ops.getByRole('row').filter({ hasText: 'guide-gate' });
  await button(row, '禁用').click();
  await summon.waitFor({ state: 'detached' });
  await button(row, '启用').click();
  await summon.click();
  assert((await chat.getByPlaceholder('发消息...').inputValue()).includes('进场'));
  assert.deepEqual(errors, []);
  console.log('PASS: eight catalog skills, customer drafts and persisted grants, isolated Agent roles, live project summon and global enable/disable.');
} finally { await browser.close(); }
